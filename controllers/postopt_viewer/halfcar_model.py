"""Half-car longitudinal/vertical model, ported from `params_opt_v2.34.jl`.

The fitted model lives in Julia. A Webots controller has to compute in-process to reach a Display
device, so the right-hand side is re-implemented here. Two copies of the same physics drift apart
silently, so `check_parity.py` asserts this port against fixtures generated by Julia:

    rhs_fixture.json        200 states with the derivative Julia computes for each   (tol 1e-10)
    trajectory_fixture.json one integration at the same RK4 substep                  (tol 1e-9)

Regenerate the fixtures with `analysis/live/export_params.jl` after any model change; the check then
fails until this file is brought back into line.

State vector, in the same order the Julia code uses:

    0 z_s      sprung mass height [m]
    1 theta    pitch, positive = nose down [rad]
    2 z_uf     front unsprung height [m]
    3 z_ur     rear unsprung height [m]
    4 x        travelled distance [m]
    5 v        longitudinal speed [m/s]
    6 dz_s     heave rate [m/s]
    7 dtheta   pitch rate [rad/s]
    8 dz_uf    front unsprung rate [m/s]
    9 dz_ur    rear unsprung rate [m/s]
"""

from __future__ import annotations

import json
import math
import os

# Two pi appears often; kept as a module constant so the constant matches Julia's `2pi` exactly.
TWO_PI = 2.0 * math.pi

# Every field the right-hand side reads, in the order `halfcar_params` returns them. The controller
# loads these from `params_opt_v2.json`, so no number is duplicated in Python.
REQUIRED_FIELDS = (
    "wheel_radius", "sprung_mass", "unsprung_front", "unsprung_rear", "pitch_inertia",
    "cg_height", "max_torque", "max_power", "gear_ratio", "engine_max_rpm", "redline_span",
    "throttle_force", "traction_acceleration",
    "brake_coefficient", "brake_scale", "brake_smoothing",
    "resistance", "resistance_smoothing", "gravity",
    "total_mass", "cg_to_front", "cg_to_rear",
    "suspension_stiffness_front", "suspension_stiffness_rear",
    "suspension_damping_front", "suspension_damping_rear",
    "tyre_stiffness_front", "tyre_stiffness_rear",
    "tyre_damping_front", "tyre_damping_rear",
    "unsprung_front_static", "unsprung_rear_static",
    "body_front_static", "body_rear_static",
    "suspension_force_front", "suspension_force_rear",
    "tyre_force_front", "tyre_force_rear",
    "static_sprung_height", "static_pitch",
)


def load_parameters(path: str) -> dict:
    """Read the fitted parameters written by `export_params.jl`.

    The payload stores every field, derived quantities included, so nothing here is recomputed from a
    subset of primaries - which is what keeps the Python model numerically identical to the Julia one.
    """
    with open(path, "r", encoding="utf-8") as handle:
        payload = json.load(handle)
    values = payload["values"]
    missing = [name for name in REQUIRED_FIELDS if name not in values]
    if missing:
        raise KeyError(f"{os.path.basename(path)} is missing fields: {missing}")
    parameters = {name: float(value) for name, value in values.items()}
    parameters["_label"] = payload.get("label", "unknown")
    parameters["_log_file"] = payload.get("log_file", "unknown")
    return parameters


def road_height(stations_x, stations_z, position: float) -> float:
    """Road height under a contact patch, linearly interpolated.

    An empty table is a perfectly flat surface, which is the case for the highway world, so this
    returns zero without any interpolation work.
    """
    if not stations_x:
        return 0.0
    if position <= stations_x[0] or position >= stations_x[-1]:
        return 0.0
    # The station table is sorted, so a binary search is the faithful equivalent of searchsortedfirst.
    low, high = 0, len(stations_x) - 1
    while low < high:
        middle = (low + high) // 2
        if stations_x[middle] < position:
            low = middle + 1
        else:
            high = middle
    upper_index = low
    lower_index = upper_index - 1
    span = stations_x[upper_index] - stations_x[lower_index]
    if span <= 0.0:
        return stations_z[lower_index]
    return (stations_z[lower_index]
            + (position - stations_x[lower_index]) / span
            * (stations_z[upper_index] - stations_z[lower_index]))


def smooth_min(a: float, b: float, k: float = 200.0) -> float:
    """Differentiable minimum, `0.5*(a + b - sqrt((a - b)**2 + k**2))`.

    Mirrors `smooth_min` in the Julia notebook exactly, including the default `k` of 200 N: the drive
    cap is compared against forces of tens of kilonewtons, so the rounded corner stays within a fraction
    of a percent of a hard minimum while remaining differentiable at the switching point.
    """
    return 0.5 * (a + b - math.sqrt((a - b) ** 2 + k ** 2))


def rhs(state, p: dict, throttle: float, brake: float, road_x=(), road_z=()):
    """Derivative of the ten-state half-car model.

    `throttle` and `brake` are scalars here because the caller holds them constant over the interval
    being integrated, which is exactly what the Julia code does by indexing its pedal arrays.
    """
    z_s, theta, z_uf, z_ur, position, velocity, dz_s, dtheta, dz_uf, dz_ur = state

    # --- longitudinal force -------------------------------------------------
    rpm = abs(velocity) / p["wheel_radius"] * p["gear_ratio"] * 60.0 / TWO_PI
    # Constant torque to the base speed, constant power beyond it.
    if rpm <= 0.0:
        torque = p["max_torque"]
    else:
        torque = min(p["max_torque"], p["max_power"] * 60.0 / (TWO_PI * rpm))
    # The redline is a tanh, not a clamp: a flat region would hide its switching point from any
    # gradient, and the edge here is abrupt in reality but must stay smooth for the fit.
    redline = 0.5 * (1.0 - math.tanh((rpm - p["engine_max_rpm"]) / p["redline_span"]))
    # The drive is capped by the vehicle library's wheel-spin guard: driver.c:52 limits wheel
    # acceleration to ACCELERATION_THRESHOLD 50 rad/s2, which on this car is about 17.9 m/s2 at the body.
    # The fitted `traction_acceleration` is the body-level equivalent. `smooth_min`, not `min`, so the
    # switching point stays differentiable - a hard minimum is C0 but not C1.
    demand = throttle * p["throttle_force"] * (torque / p["max_torque"]) * redline
    drive = smooth_min(demand, p["traction_acceleration"] * p["total_mass"])
    # One resistance term, proportional to speed. With both pedals at zero the recorded deceleration is
    # a least-squares fit of F = -141*v, so it scales with speed and has no constant part. The tanh
    # carries the sign and keeps the force smooth through standstill, so it can never run the car
    # backwards.
    resistance = (p["resistance"] * abs(velocity)
                  * math.tanh(velocity / p["resistance_smoothing"]))
    # Constant-torque brake, matching `halfcar_rhs!` in params_opt_v2.34.jl: the pad torque is set by the
    # pedal and is independent of road speed, which is what the Webots vehicle library produces by
    # dividing its damping constant by the wheel speed. `tanh` fades it to zero at standstill so it can
    # never push the car backwards, standing in for the `1/omega` blow-up the library relies on.
    # No grip cap: the fitted `brake_scale` already lands below what the tyres can transmit, so a cap
    # would only add a parameter that cannot be identified.
    brake_force = (4.0 * p["brake_coefficient"] * p["brake_scale"] * brake / p["wheel_radius"]
                   * math.tanh(velocity / p["brake_smoothing"]))
    longitudinal = drive - brake_force - resistance

    # --- vertical forces, as perturbations about the measured static ride ---
    body_front = z_s - p["cg_to_front"] * theta
    body_rear = z_s + p["cg_to_rear"] * theta
    road_front = road_height(road_x, road_z, position + p["cg_to_front"])
    road_rear = road_height(road_x, road_z, position - p["cg_to_rear"])
    suspension_front = (p["suspension_force_front"]
                        + p["suspension_stiffness_front"]
                        * ((z_uf - p["unsprung_front_static"]) - (body_front - p["body_front_static"]))
                        + p["suspension_damping_front"]
                        * (dz_uf - (dz_s - p["cg_to_front"] * dtheta)))
    suspension_rear = (p["suspension_force_rear"]
                       + p["suspension_stiffness_rear"]
                       * ((z_ur - p["unsprung_rear_static"]) - (body_rear - p["body_rear_static"]))
                       + p["suspension_damping_rear"]
                       * (dz_ur - (dz_s + p["cg_to_rear"] * dtheta)))
    tyre_front = (p["tyre_force_front"]
                  + p["tyre_stiffness_front"] * (road_front - (z_uf - p["unsprung_front_static"]))
                  - p["tyre_damping_front"] * dz_uf)
    tyre_rear = (p["tyre_force_rear"]
                 + p["tyre_stiffness_rear"] * (road_rear - (z_ur - p["unsprung_rear_static"]))
                 - p["tyre_damping_rear"] * dz_ur)

    # A positive pitch is nose down, so a forward force at ground level pitches the body up.
    pitch_moment = (-p["cg_to_front"] * suspension_front
                    + p["cg_to_rear"] * suspension_rear
                    - p["cg_height"] * longitudinal)

    return [
        dz_s,
        dtheta,
        dz_uf,
        dz_ur,
        velocity,
        longitudinal / p["total_mass"],
        (suspension_front + suspension_rear - p["sprung_mass"] * p["gravity"]) / p["sprung_mass"],
        pitch_moment / p["pitch_inertia"],
        (tyre_front - suspension_front - p["unsprung_front"] * p["gravity"]) / p["unsprung_front"],
        (tyre_rear - suspension_rear - p["unsprung_rear"] * p["gravity"]) / p["unsprung_rear"],
    ]


def rk4_step(state, p: dict, throttle: float, brake: float, dt: float, road_x=(), road_z=()):
    """One classical RK4 step. The same scheme the Julia reference integrator uses."""
    k1 = rhs(state, p, throttle, brake, road_x, road_z)
    stage = [state[i] + 0.5 * dt * k1[i] for i in range(10)]
    k2 = rhs(stage, p, throttle, brake, road_x, road_z)
    stage = [state[i] + 0.5 * dt * k2[i] for i in range(10)]
    k3 = rhs(stage, p, throttle, brake, road_x, road_z)
    stage = [state[i] + dt * k3[i] for i in range(10)]
    k4 = rhs(stage, p, throttle, brake, road_x, road_z)
    return [state[i] + dt / 6.0 * (k1[i] + 2.0 * k2[i] + 2.0 * k3[i] + k4[i]) for i in range(10)]


# The tyre hop is the fastest mode: sqrt(2 * tyre_spring / unsprung_mass) ~ 105 rad/s for this car.
# RK4 is stable while dt * omega < 2.8, so the limit is about 27 ms. 1 ms gives a 27x margin, and its
# local error (omega dt)^5 / 5! is ~1e-8 against ~3e-4 for a single 5 ms step - which is why the
# physics step is subdivided rather than integrated in one go.
SUBSTEPS = 5


def advance(state, p: dict, throttle: float, brake: float, dt: float,
            substeps: int = SUBSTEPS, road_x=(), road_z=()):
    """Advance one measurement interval, subdividing it internally."""
    inner = dt / substeps
    for _ in range(substeps):
        state = rk4_step(state, p, throttle, brake, inner, road_x, road_z)
    return state


def initial_state(p: dict, com_z: float, pitch: float, position: float, speed: float):
    """State for the start of a segment.

    `com_z`, `pitch`, `position` and `speed` are measured, so they are used directly. The two unsprung
    heights are not measured, so each is placed at the quasi-static equilibrium implied by the body
    position - the same construction `halfcar_segment_history` uses. All four rates start at zero.
    """
    body_front = com_z - p["cg_to_front"] * pitch
    body_rear = com_z + p["cg_to_rear"] * pitch
    front_offset = ((body_front - p["body_front_static"]) * p["suspension_stiffness_front"]
                    / (p["suspension_stiffness_front"] + p["tyre_stiffness_front"]))
    rear_offset = ((body_rear - p["body_rear_static"]) * p["suspension_stiffness_rear"]
                   / (p["suspension_stiffness_rear"] + p["tyre_stiffness_rear"]))
    return [
        com_z, pitch,
        p["unsprung_front_static"] + front_offset,
        p["unsprung_rear_static"] + rear_offset,
        position, speed,
        0.0, 0.0, 0.0, 0.0,
    ]


def com_height(state, p: dict) -> float:
    """Centre-of-mass height, the quantity the measurement `com_z` corresponds to."""
    return (p["sprung_mass"] * state[0]
            + p["unsprung_front"] * state[2]
            + p["unsprung_rear"] * state[3]) / p["total_mass"]
